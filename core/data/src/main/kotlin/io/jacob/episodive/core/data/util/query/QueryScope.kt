package io.jacob.episodive.core.data.util.query

/**
 * 같은 조건의 목록을 **몇 개까지 캐시해 둘 것인지**를 가르는 축.
 *
 * 캐시 키에 이 값이 들어가야 홈의 미리보기와 '더 보기' 전체 목록이 서로 다른 그룹이 된다.
 * 키를 공유하면 홈이 먼저 10개를 채운 뒤 TTL 안에는 갱신이 일어나지 않아
 * ([RemoteUpdater.refreshIfNeeded]), 전체 목록도 그 10개만 보게 된다 — 페이징 소스는
 * 개수 제한 없이 그룹 전체를 그대로 읽기 때문이다.
 *
 * 반대로 원격 요청 크기를 [PREVIEW] 쪽에 맞춰 키를 하나로 통일하면, 아무도 더 보기를
 * 누르지 않아도 홈이 매 갱신마다 전체 목록만큼의 비용을 낸다. 트렌딩·최근 경로는 피드마다
 * 상세 요청이 한 번씩 더 붙어서 그 차이가 특히 크다.
 */
enum class QueryScope(val value: String) {
    /** 홈 섹션이 쓰는 미리보기. 항목 수가 적고 자주 갱신된다. */
    PREVIEW("preview"),

    /** '더 보기' 전체 목록. 사용자가 실제로 요구했을 때만 채워진다. */
    FULL("full"),
}
